"""Decision and reason codes.

A short entry is intentionally absent. Long equity is the only entry.
Decisions are ENTER_LONG and NO_TRADE. Margin is rejected when config loads.
"""

from __future__ import annotations

from enum import Enum


class DecisionKind(str, Enum):
    ENTER_LONG = "ENTER_LONG"
    NO_TRADE = "NO_TRADE"


